"""Generate every numeric table used in docs/PHASE1_MATH_AND_MECHANICS.md from the simulator.

All rows are HYPOTHETICAL calculations on the verified curve parameters (no market data),
except section G, which summarises one replayed real launch (n = 1, illustrative only).
Usage: python -m scripts.phase1_tables [--sol-usd 95.80]   -> docs/generated/phase1_tables.md
"""
from __future__ import annotations

import argparse
import json
import pathlib

from pumpsim import VERIFIED, CurveState
from pumpsim.analysis import (
    batch_sell, break_even_external_integer, cf_break_even_external, cf_marginal_capture,
    external_demand_scenario, liquidation_value, round_trip,
)
from pumpsim.costs import BASE_FEE_ONLY, TYPICAL, AGGRESSIVE, ExecutionCosts
from pumpsim.curve import CurveParams, buy_exact_quote_in, sell_exact_tokens_in

L = 10**9
ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "generated" / "phase1_tables.md"
SCHED = VERIFIED.fee_schedule


def sol(x: float, d: int = 4) -> str:
    return f"{x / L:,.{d}f}"


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---:" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sol-usd", type=float, default=95.80, help="SOL/USD for USD columns (2026-10-31 Kraken/Coinbase)")
    a = ap.parse_args()
    usd = a.sol_usd
    md = [f"# Phase 1 generated tables\n\nGenerated by `python -m scripts.phase1_tables --sol-usd {usd}`. "
          "All values are hypothetical calculations on the verified curve unless stated. "
          "1 SOL = 1e9 lamports; tokens shown in whole tokens (1e6 base units).\n"]
    fresh = CurveState.fresh(VERIFIED)

    # A. Round trip, no other trades -------------------------------------------------
    rows = []
    for g in (1, 2, 5, 10, 20):
        b = buy_exact_quote_in(fresh, g * L, SCHED)
        rt = round_trip(VERIFIED, g * L, 1, ExecutionCosts(signatures_per_tx=0))
        rtc = round_trip(VERIFIED, g * L, 1, ExecutionCosts(signatures_per_tx=0), operator_is_creator=True)
        rows.append([g, f"{b.tokens / 1e6:,.0f}", f"{b.tokens / VERIFIED.token_total_supply:.2%}",
                     f"{b.after.market_cap() / L:,.2f} (${b.after.market_cap() / L * usd:,.0f})",
                     sol(rt.recovered), sol(rt.curve_loss), f"{rt.curve_loss / (g * L):.3%}",
                     sol(rtc.net_loss), f"{rtc.net_loss / (g * L):.3%}"])
    md.append("## A. Immediate round trip on a fresh curve, nobody else trades (curve + platform fees only)\n")
    md.append(table(["Spend (SOL)", "Tokens bought", "% of supply", "Mcap after buy, SOL (USD)", "SOL back",
                     "Loss (SOL)", "Loss %", "Loss if you are the creator (SOL)", "Creator loss %"], rows))
    md.append("\nCreator column: the 0.30 % creator fee on your own buy and sell accrues to your creator vault "
              "(claimable); network cost of claiming excluded here.\n")

    # A2. Network-cost overlay ---------------------------------------------------------
    rows = []
    for label, c in (("base fee only", BASE_FEE_ONLY), ("TYPICAL (20k priority)", TYPICAL),
                     ("AGGRESSIVE (0.001 SOL prio + 0.001 SOL tip)", AGGRESSIVE),
                     ("AGGRESSIVE + 30 % failure", ExecutionCosts(1_000_000, 1_000_000, failure_rate=0.3))):
        for w in (1, 5, 10):
            rt = round_trip(VERIFIED, 10 * L, w, c)
            rows.append([label, w, sol(rt.curve_loss), sol(rt.network, 6), sol(rt.net_loss), f"{rt.net_loss / (10 * L):.3%}"])
    md.append("## A2. 10 SOL round trip with network-cost assumptions and wallet count\n")
    md.append(table(["Cost assumption", "Wallets", "Curve+platform loss", "Network cost", "Total loss (SOL)", "Total %"], rows))
    md.append("\nRent for token accounts / volume accumulators is excluded (refundable on close). "
              "With rent locked and not reclaimed: +0.00286 SOL per wallet (Token-2022 ATA + accumulator).\n")

    # B. External demand ---------------------------------------------------------------
    rows = []
    for x in (0, 0.25, 0.5, 0.58, 1, 2, 5, 10, 20, 50):
        if x == 0:
            rt = round_trip(VERIFIED, 10 * L)
            first = {"operator_net_pnl": -rt.net_loss, "externals_curve_pnl": 0}
            last = first
        else:
            first = external_demand_scenario(VERIFIED, 10 * L, [int(x * L)])
            last = external_demand_scenario(VERIFIED, 10 * L, [int(x * L)], operator_exits_first=False)
        half = external_demand_scenario(VERIFIED, 10 * L, [int(x * L)], external_sell_fraction_before_exit=0.5) if x else first
        rows.append([x, sol(first["operator_net_pnl"]), sol(first["externals_curve_pnl"]),
                     sol(half["operator_net_pnl"]), sol(last["operator_net_pnl"])])
    md.append("## B. 10 SOL operator buys first; independent buyers then spend X SOL\n")
    md.append(table(["External spend X (SOL)", "Operator P&L, exits first", "Externals' P&L (they exit after)",
                     "Operator P&L, externals sell half first", "Operator P&L, externals exit first"], rows))
    md.append("\nBase fee 5,000 lamports per transaction included; no priority fees. Not the creator (no creator-fee income).\n")

    # C. Break-even ----------------------------------------------------------------------
    rows = []
    for g in (1, 2, 5, 10, 20):
        n = g / 1.0125
        xi = break_even_external_integer(VERIFIED, g * L, costs=ExecutionCosts(signatures_per_tx=0))
        xc = break_even_external_integer(VERIFIED, g * L, costs=ExecutionCosts(signatures_per_tx=0), operator_is_creator=True)
        rows.append([g, f"{cf_break_even_external(n, 30, 0.0125, 0.0125):.4f}", sol(xi), f"{xi / (g * L):.2%}", sol(xc),
                     f"{cf_marginal_capture(n, 30):.3f}"])
    md.append("## C. External buying needed for the operator to break even (fees only, operator exits first)\n")
    md.append(table(["Operator spend (SOL)", "Closed-form X* net (SOL)", "Exact external spend (SOL)",
                     "as % of operator spend", "Exact, if operator is creator (SOL)", "Capture rate of first external SOL"], rows))
    md.append("\nThe break-even assumes the external buyers hold while the operator sells. Their loss is the operator's gain.\n")

    # D. Sensitivity to starting virtual reserves (starting market cap) ---------------------
    rows = []
    for vq in (10, 20, 30, 60, 100):
        p = CurveParams(VERIFIED.initial_virtual_token_reserves, vq * L, VERIFIED.initial_real_token_reserves,
                        VERIFIED.token_total_supply, VERIFIED.pool_migration_fee, SCHED)
        s0 = CurveState.fresh(p)
        b = buy_exact_quote_in(s0, 10 * L, SCHED)
        rt = round_trip(p, 10 * L, 1, ExecutionCosts(signatures_per_tx=0))
        xi = break_even_external_integer(p, 10 * L, costs=ExecutionCosts(signatures_per_tx=0))
        rows.append([vq, f"{s0.market_cap() / L:,.1f} (${s0.market_cap() / L * usd:,.0f})",
                     f"{b.tokens / VERIFIED.token_total_supply:.2%}", f"{b.after.market_cap() / s0.market_cap():.2f}x",
                     f"{rt.curve_loss / (10 * L):.3%}", sol(xi)])
    md.append("## D. Does the starting market cap matter? (10 SOL buy; V = initial virtual SOL)\n")
    md.append(table(["V (SOL)", "Start mcap SOL (USD)", "Supply bought", "Mcap multiple after buy",
                     "Round-trip loss %", "Break-even external spend (SOL)"], rows))
    md.append("\nOnly V = 30 SOL is live for SOL-paired coins; other rows are counterfactual sensitivity only. "
              "USDC-paired coins start at 4,292 USDC virtual (US$4,000 mcap).\n")

    # E. Liquidation value calculator --------------------------------------------------
    b = buy_exact_quote_in(fresh, 10 * L, SCHED)
    after_ext = buy_exact_quote_in(b.after, 5 * L, SCHED).after
    rows = []
    for label, st in (("Right after own 10 SOL buy", b.after), ("After +5 SOL of external buys", after_ext)):
        lv = liquidation_value(st, b.tokens, SCHED, TYPICAL, cost_basis=10 * L)
        rows.append([label, f"{lv['displayed_market_cap'] / L:,.2f} (${lv['displayed_market_cap'] / L * usd:,.0f})",
                     sol(lv["displayed_position_value_at_spot"]), sol(lv["theoretical_curve_value_no_fees"]),
                     f"{lv['price_impact_vs_spot']:.2%}", sol(lv["protocol_fee"] + lv["creator_fee"]),
                     sol(lv["net_sol_recovered"]), sol(lv["net_pnl"])])
    md.append("## E. Liquidation value of the 10 SOL position (265,758,514 tokens), one sell, nobody ahead\n")
    md.append(table(["State", "Displayed mcap SOL (USD)", "Displayed position value", "Curve value (no fees)",
                     "Price impact vs spot", "Platform fees", "Net SOL recovered", "Net P&L"], rows))
    md.append("\nTYPICAL network cost assumption (5,000 base + 20,000 priority lamports).\n")

    # F. Multi-wallet batch selling ---------------------------------------------------------
    st, bals = fresh, []
    for _ in range(5):
        r = buy_exact_quote_in(st, 2 * L, SCHED)
        st, bals = r.after, bals + [r.tokens]
    one = sell_exact_tokens_in(st, sum(bals), SCHED).user_quote_delta - TYPICAL.per_attempt()
    rows = [["single wallet holding everything", "-", "1/1", sol(one), "0"]]
    for basis in ("pre_batch", "sequential"):
        for tol in (100, 500, 1500, 3000):
            res = batch_sell(st, bals, SCHED, tol, basis, TYPICAL)
            okc = sum(r["ok"] for r in res["rows"])
            rows.append([f"5 wallets, min_out from {basis.replace('_', '-')} quote", f"{tol / 100:.0f}%", f"{okc}/5",
                         sol(res["total_net"]), f"{res['unsold_tokens'] / 1e6:,.0f}"])
    ext = batch_sell(st, bals, SCHED, 3000, "pre_batch", TYPICAL, interleave={2: ("sell", 30_000_000_000_000)})
    rows.append(["5 wallets, pre-batch quote, external dumps 30M tokens before wallet 3", "30%",
                 f"{sum(r['ok'] for r in ext['rows'])}/5", sol(ext["total_net"]), f"{ext['unsold_tokens'] / 1e6:,.0f}"])
    md.append("## F. Selling 10 SOL of tokens held in 5 wallets (2 SOL each), executed in one slot in list order\n")
    md.append(table(["Method", "Slippage tolerance", "Sells landed", "Net SOL recovered", "Tokens left unsold"], rows))
    prices = [round(r["avg_price_lamports_per_token"], 2) for r in batch_sell(st, bals, SCHED, 10_000, "sequential")["rows"]]
    md.append(f"\nSame slot, different prices: average execution price per wallet (lamports per token), in order: {prices}.\n")

    # H. Third party inserted between your own (non-atomic) buys --------------------------
    from pumpsim.analysis import Simulation
    rows = []
    for label, sniper_sol, sniper_sells_before_you in (
            ("No interleaving (atomic bundle or single tx)", 0, True),
            ("1 SOL buy after wallet 1; sells before your exit", 1, True),
            ("3 SOL buy after wallet 1; sells before your exit", 3, True),
            ("3 SOL buy after wallet 1; holds, you exit first", 3, False)):
        sim = Simulation(VERIFIED)
        for i in range(5):
            sim.buy(f"w{i}", 2 * L)
            if i == 0 and sniper_sol:
                sim.buy("third", sniper_sol * L)
        if sniper_sol and sniper_sells_before_you:
            sim.sell("third")
        for i in range(5):
            sim.sell(f"w{i}")
        if sniper_sol and not sniper_sells_before_you:
            sim.sell("third")
        op = sum(sim.parties[f"w{i}"].curve_pnl for i in range(5))
        th = sim.parties["third"].curve_pnl if sniper_sol else 0
        rows.append([label, sol(op), sol(th)])
    md.append("## H. 10 SOL bought through 5 wallets in separate transactions; a third party gets in between\n")
    md.append(table(["Sequence", "Your curve P&L (SOL)", "Third party's curve P&L (SOL)"], rows))
    md.append("\nCurve + platform fees only. Non-atomic multi-wallet buying hands the 'between' position to whoever "
              "can insert a transaction; a single transaction or an all-or-nothing bundle removes that gap.\n")

    # I. Exact 10 SOL reversibility ledger ------------------------------------------------
    b = buy_exact_quote_in(fresh, 10 * L, SCHED)
    sl = sell_exact_tokens_in(b.after, b.tokens, SCHED)
    def st_row(name, st):
        return [name, f"{st.virtual_quote_reserves:,}", f"{st.real_quote_reserves:,}", f"{st.virtual_token_reserves:,}",
                f"{st.real_token_reserves:,}"]
    md.append("## I. Exact integer ledger: buy with 10 SOL, sell the same tokens back, nobody else trades\n")
    md.append(table(["State", "virtual SOL (lamports)", "real SOL (lamports)", "virtual tokens (base units)",
                     "real tokens (base units)"], [st_row("initial", fresh), st_row("after buy", b.after),
                                                   st_row("after sell", sl.after)]))
    md.append("\n" + table(["Item", "Lamports"], [
        ["SOL budget (buy_exact_sol_in)", f"{10 * L:,}"],
        ["net SOL into curve", f"{b.quote_curve:,}"],
        ["buy protocol fee (0.95 %)", f"{b.protocol_fee:,}"],
        ["buy creator fee (0.30 %)", f"{b.creator_fee:,}"],
        ["total paid", f"{-b.user_quote_delta:,}"],
        ["tokens received (base units)", f"{b.tokens:,}"],
        ["gross SOL out of curve on sell", f"{sl.quote_curve:,}"],
        ["sell protocol fee", f"{sl.protocol_fee:,}"],
        ["sell creator fee", f"{sl.creator_fee:,}"],
        ["SOL received", f"{sl.user_quote_delta:,}"],
        ["net loss (curve + platform fees)", f"{-b.user_quote_delta - sl.user_quote_delta:,}"],
        ["  of which platform fees", f"{b.total_fee + sl.total_fee:,}"],
        ["  of which rounding dust left in curve", f"{sl.after.real_quote_reserves:,}"],
    ]))

    # G. One real launch (illustrative, n = 1) -----------------------------------------------
    replays = sorted((ROOT / "data" / "replays").glob("*.json"))
    if replays:
        md.append("## G. One replayed real launch (VERIFIED on-chain data, n = 1, not representative)\n")
        for path in replays:
            d = json.loads(path.read_text())
            tr = d["trades"]
            peak = max(tr, key=lambda r: r["mcap_sol_after"])
            cre = [r for r in tr if r["is_creator"]]
            md.append(f"- Mint `{d['mint']}`: {d['trades_replayed']} trades replayed from creation, "
                      f"{d['trades_exact_match']} exact matches; {d['signatures_failed']} of {d['signatures_total']} "
                      f"transactions touching the curve failed; {d['distinct_traders']} distinct trader wallets.")
            md.append(f"  Creator trades: {len(cre)} ({', '.join(f'{r['side']} {r['sol_curve'] / L:.3f} SOL at t={r['t']}s' for r in cre[:4])}). "
                      f"Peak mcap {peak['mcap_sol_after']:.1f} SOL at t={peak['t']}s; last observed mcap "
                      f"{tr[-1]['mcap_sol_after']:.1f} SOL at t={tr[-1]['t']}s.")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n\n".join(md) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
